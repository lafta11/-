-- Run this in Supabase SQL Editor for the prototype.
-- Public reports are visible to all visitors; inserts are anonymous.
-- Before a public launch, add rate limiting, abuse controls, and moderation.
create table if not exists public.road_reports (
  id bigint generated by default as identity primary key,
  kind text not null check (kind in ('traffic','accident','hazard','closure','works')),
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  note text not null default '' check (char_length(note) <= 240),
  created_at timestamptz not null default now(),
  expires_at timestamptz not null default (now() + interval '4 hours'),
  confirmations integer not null default 0 check (confirmations >= 0)
);

create index if not exists road_reports_expires_idx on public.road_reports (expires_at);
create index if not exists road_reports_created_idx on public.road_reports (created_at desc);

alter table public.road_reports enable row level security;

drop policy if exists "Anyone can read active road reports" on public.road_reports;
create policy "Anyone can read active road reports"
on public.road_reports for select to anon, authenticated
using (expires_at > now());

drop policy if exists "Anyone can submit a road report" on public.road_reports;
create policy "Anyone can submit a road report"
on public.road_reports for insert to anon, authenticated
with check (
  kind in ('traffic','accident','hazard','closure','works')
  and lat between -90 and 90
  and lng between -180 and 180
  and expires_at <= now() + interval '5 hours'
  and expires_at > now()
);

-- Enable Realtime for the table in Supabase Dashboard > Database > Publications,
-- or run the following if your project uses the standard supabase_realtime publication:
alter publication supabase_realtime add table public.road_reports;
